export const ITEMS = STRENGTHS.flatMap((s, si) => s.items.map((text, j) => ({
  id: 'S' + String(si * 4 + j + 1).padStart(2, '0'),
  strength: s.key,
  text,
  options: OPTIONS
})));

const avg = xs => xs.reduce((a, b) => a + b, 0) / xs.length;

// 반환: { strengths: [{key,name,virtue,def,score}], virtues: [{key,name,score}] }
export function score(answers) {
  const strengths = STRENGTHS.map(s => {
    const vals = ITEMS.filter(it => it.strength === s.key).map(it => answers[it.id]);
    if (vals.length !== 4 || vals.some(v => typeof v !== 'number')) throw new Error('incomplete');
    return { key: s.key, name: s.name, virtue: s.virtue, def: s.def, score: avg(vals) };
  });
  const virtues = VIRTUES.map(v => ({ ...v, score: avg(strengths.filter(s => s.virtue === v.key).map(s => s.score)) }));
  return { strengths, virtues };
}
