// N01~N05 → 1영역, N06~N10 → 2영역 … (5문항씩)
export const ITEMS = T.map((text, i) => ({
  id: 'N' + String(i + 1).padStart(2, '0'),
  domain: DOMAINS[Math.floor(i / 5)].key,
  text,
  options: OPTIONS
}));

// 반환: [{ key, name, desc, score }] (원래 영역 순서, 1.00~5.00)
export function score(answers) {
  return DOMAINS.map(d => {
    const vals = ITEMS.filter(it => it.domain === d.key).map(it => answers[it.id]);
    if (vals.length !== 5 || vals.some(v => typeof v !== 'number')) throw new Error('incomplete');
    return { ...d, score: vals.reduce((a, b) => a + b, 0) / 5 };
  });
}
